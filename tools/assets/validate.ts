import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { CONTEXT_RATE } from '../../src/shared/audio';
import { Manifest } from '../../src/shared/manifest';
import { type AudioMeasure, checkAudioFiles, checkAudioManifest } from './check/audio';
import {
  audioAccount,
  BUDGET,
  checkBudgets,
  gpuAccount,
  initialDownload,
  offlineDownload,
  total,
  voiceDownload,
} from './check/budgets';
import { checkFiles, referencedFiles } from './check/files';
import { error, type Finding } from './check/finding';
import { checkMaps, loadMaps } from './check/maps';
import { checkSpeechFiles, checkSpeechManifest, type SpeechMeasure } from './check/speech';
import { checkUnicorns } from './check/unicorns';

/**
 * `pnpm assets:validate`: proves the generated assets are the ones the game will look for, in the
 * shape it will use them, and inside the size budgets. It fails the build on any error. `--report
 * <file>` also writes the asset report as Markdown.
 */

const MiB = 1024 * 1024;
const mib = (n: number): string => (n / MiB).toFixed(2);

export interface Validation {
  findings: Finding[];
  report: string;
}

export function validate(dir: string): Validation {
  const manifestPath = join(dir, 'manifest.json');
  if (!existsSync(manifestPath))
    return { findings: [error('manifest', `${manifestPath} does not exist: run pnpm assets:build first`)], report: '' };
  const parsed = Manifest.safeParse(JSON.parse(readFileSync(manifestPath, 'utf8')));
  if (!parsed.success)
    return {
      findings: [
        error(
          'manifest',
          `the manifest is not valid: ${parsed.error.issues
            .slice(0, 3)
            .map((i) => `${i.path.join('.')}: ${i.message}`)
            .join('; ')}`,
        ),
      ],
      report: '',
    };
  const manifest = parsed.data;

  const findings: Finding[] = [...checkFiles(dir, manifest)];
  // Nothing past this point can be trusted if files are missing, so stop at the first sign.
  if (findings.length > 0) return { findings, report: '' };
  const maps = loadMaps(dir, manifest);
  findings.push(...checkMaps(dir, manifest));
  findings.push(...checkUnicorns(manifest));
  if (!manifest.audio) findings.push(error('audio', 'the manifest has no audio: run pnpm assets:build'));
  let measured: AudioMeasure | null = null;
  let spoken: SpeechMeasure | null = null;
  if (manifest.audio) {
    findings.push(...checkAudioManifest(manifest.audio));
    const files = checkAudioFiles(dir, manifest.audio);
    findings.push(...files.found);
    measured = files.measured;
    findings.push(...checkSpeechManifest(manifest.audio));
    const voice = checkSpeechFiles(dir, manifest.audio);
    findings.push(...voice.found);
    spoken = voice.measured;
  }
  findings.push(...checkBudgets(dir, manifest, maps));
  return { findings, report: writeReport(dir, manifest, findings, measured, spoken) };
}

function writeReport(
  dir: string,
  manifest: Manifest,
  findings: Finding[],
  measured: AudioMeasure | null,
  spoken: SpeechMeasure | null,
): string {
  const maps = loadMaps(dir, manifest);
  const files = referencedFiles(manifest);
  const kinds: [string, (f: string) => boolean][] = [
    ['Unicorn atlases', (f) => f.startsWith('unicorns/')],
    ['Grown-up atlases', (f) => f.startsWith('npcs/')],
    ['Scenery and tile sheets', (f) => f.startsWith('bundles/')],
    ['Compiled maps', (f) => f.startsWith('maps/')],
    ['Music and ambience', (f) => /^audio\/(music|ambience)-/.test(f)],
    ['Sound effect sheets', (f) => f.startsWith('audio/sheet-')],
    ['Spoken clips', (f) => f.startsWith('speech/')],
  ];
  const cost = new Map(
    [...offlineDownload(dir, manifest), ...voiceDownload(dir, manifest)].map((c) => [c.file, c.bytes]),
  );
  const lines: string[] = [];
  const out = (s = ''): number => lines.push(s);

  out('# Asset report');
  out();
  out('Generated by `pnpm assets:validate --report`. Do not edit by hand: run the command again.');
  out();
  out(`Content version ${manifest.contentVersion}.`);
  out();
  out('## Budgets');
  out();
  const initial = total(initialDownload(dir, manifest, maps));
  const offline = total(offlineDownload(dir, manifest));
  const voice = total(voiceDownload(dir, manifest));
  const gpu = gpuAccount(manifest, maps);
  out('| What | Measured | Target |');
  out('|---|---|---|');
  out(`| First playable download, assets only | ${mib(initial)} MiB | ${mib(BUDGET.initial)} MiB |`);
  out(`| The game kept for offline play, assets only | ${mib(offline)} MiB | ${mib(BUDGET.offline)} MiB |`);
  out(`| The spoken lessons, kept as they are heard or all at once | ${mib(voice)} MiB | ${mib(BUDGET.voice)} MiB |`);
  out(
    `| Graphics memory at its peak, between ${gpu.peakBetween.join(' and ')}, showing eight facings | ${mib(gpu.peak)} MiB | ${mib(BUDGET.gpu)} MiB |`,
  );
  out(
    `| The same with the fine facings of all six unicorns loaded | ${mib(gpu.peakWithFine)} MiB | ${mib(BUDGET.gpuFine)} MiB |`,
  );
  if (manifest.audio) {
    const wanted = audioAccount(manifest.audio, maps, CONTEXT_RATE);
    const native = audioAccount(manifest.audio, maps, 48000);
    out(
      `| Decoded audio in a crossfade at ${CONTEXT_RATE / 1000} kHz, the rate the game asks for, with the voice's share | ${mib(wanted.crossfade)} MiB | ${mib(BUDGET.audio)} MiB |`,
    );
    out(
      `| Decoded audio at the least it can get down to at 48 kHz | ${mib(native.floor)} MiB | ${mib(BUDGET.audio)} MiB |`,
    );
  }
  out();
  out(
    'The app itself (scripts, styles, fonts) is not counted here, and neither is graphics memory for the canvas. Sizes of text are as sent compressed; pictures and sound are already compressed. Memory is counted from the actual dimensions as RGBA8 with no mipmaps and from decoded float samples, not from file sizes. Nothing here is a measurement of a running browser.',
  );
  out();
  out('## Files');
  out();
  out('| Kind | Files | Bytes sent |');
  out('|---|---|---|');
  for (const [name, test] of kinds) {
    const mine = files.filter(test);
    out(
      `| ${name} | ${mine.length} | ${mine.reduce((sum, f) => sum + (cost.get(f) ?? 0), 0).toLocaleString('en-US')} |`,
    );
  }
  out(`| Manifest | 1 | ${(cost.get('manifest.json') ?? 0).toLocaleString('en-US')} |`);
  out();
  out('## Graphics memory');
  out();
  out(
    `The six unicorns and the effects stay in memory: ${mib(gpu.shared)} MiB. A device that shows the fine facings holds ${mib(gpu.fine)} MiB more for the six. Each map adds its own while it is shown.`,
  );
  out();
  out('| Map | Adds |');
  out('|---|---|');
  for (const [id, bytes] of Object.entries(gpu.perMap)) out(`| ${id} | ${mib(bytes)} MiB |`);
  out();
  if (manifest.audio) {
    out('## Audio');
    out();
    out('| Loop | Seconds | LUFS | True peak | Repeat match | Repeat lag (samples) |');
    out('|---|---|---|---|---|---|');
    for (const [id, loop] of Object.entries(manifest.audio.loops)) {
      const m = measured?.loops[id];
      out(
        `| ${id} | ${loop.seconds} | ${(m?.lufs ?? loop.lufs).toFixed(1)} | ${(m?.truePeak ?? loop.truePeak).toFixed(1)} dBTP | ${m ? m.joinMatch.toFixed(4) : 'not measured'} | ${m ? m.joinLag : 'not measured'} |`,
      );
    }
    out();
    out('| Sheet | Sounds | Seconds | Bytes |');
    out('|---|---|---|---|');
    for (const [id, sheet] of Object.entries(manifest.audio.sheets))
      out(
        `| ${id} | ${Object.keys(sheet.sprites).length} | ${sheet.seconds.toFixed(1)} | ${sheet.bytes.toLocaleString('en-US')} |`,
      );
    out();
    out(
      measured
        ? 'Loudness, true peak, loop joins and sound windows were measured on the decoded MP3 files, not on the masters.'
        : 'The audio files were not decoded in this run because ffmpeg was not available. Only the manifest was checked.',
    );
    out(
      'Nobody has listened to these sounds yet. The measurements say they are the right loudness and join cleanly; they do not say they sound good.',
    );
    out();
    const clips = Object.values(manifest.audio.speech?.clips ?? {});
    out('## Voice');
    out();
    if (clips.length === 0) out('The manifest has no speech.');
    else {
      out(
        `The game speaks from ${clips.length} clips made by a speech model offline and shipped as files, in the voice ${manifest.audio.speech!.voice}. No voice of the device is used.`,
      );
      out();
      out('| Clips | Seconds of speech | Bytes | Quietest | Loudest | Longest |');
      out('|---|---|---|---|---|---|');
      const secs = clips.reduce((sum, c) => sum + c.seconds, 0);
      const bytes = clips.reduce((sum, c) => sum + c.bytes, 0);
      out(
        `| ${clips.length} | ${secs.toFixed(1)} | ${bytes.toLocaleString('en-US')} | ${spoken ? `${spoken.quietest.id} ${spoken.quietest.lufs.toFixed(1)} LUFS` : 'not measured'} | ${spoken ? `${spoken.loudest.id} ${spoken.loudest.lufs.toFixed(1)} LUFS` : 'not measured'} | ${spoken ? `${spoken.longest.id} ${spoken.longest.seconds.toFixed(2)} s` : 'not measured'} |`,
      );
      out();
      out(
        spoken
          ? 'Size, length, loudness, peak and the quiet at both ends of every clip were measured on the decoded MP3 files.'
          : 'The speech files were not decoded in this run because ffmpeg was not available. Only the manifest was checked.',
      );
      out(
        'Nobody has listened to the voice yet. Two recognisers heard each clip say what it should when it was made, which is evidence it is clear and not that it is pleasant.',
      );
      out();
    }
  }
  out('## Findings');
  out();
  if (findings.length === 0) out('None.');
  for (const f of findings) out(`- ${f.level === 'error' ? 'Error' : 'Warning'} (${f.check}): ${f.message}`);
  out();
  return lines.join('\n');
}

function main(): void {
  const args = process.argv.slice(2);
  const at = (flag: string): string | undefined => {
    const i = args.indexOf(flag);
    return i >= 0 ? args[i + 1] : undefined;
  };
  const dir = at('--assets') ?? 'public/assets';
  const { findings, report } = validate(dir);
  for (const f of findings) console.log(`${f.level === 'error' ? 'ERROR' : 'warning'} [${f.check}] ${f.message}`);
  const errors = findings.filter((f) => f.level === 'error').length;
  const reportPath = at('--report');
  if (reportPath && report) {
    mkdirSync(dirname(reportPath), { recursive: true });
    writeFileSync(reportPath, report);
    console.log(`wrote ${reportPath}`);
  }
  if (errors > 0) {
    console.error(`assets:validate found ${errors} problem${errors === 1 ? '' : 's'}`);
    process.exit(1);
  }
  console.log(
    `assets:validate passed${findings.length > 0 ? ` with ${findings.length} warning${findings.length === 1 ? '' : 's'}` : ''}`,
  );
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main();
